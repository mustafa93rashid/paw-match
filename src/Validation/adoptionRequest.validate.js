// validation/adoptionRequest.validate.js

const {
  body,
  param,
  query,
  validationResult,
} = require("express-validator");

// ==================================================
// Adoption Request Statuses
// ==================================================
// • Contains all supported adoption request statuses.
// • Used to avoid repeating status values in validations.
// ==================================================

const requestStatuses = [
  "pendingReview",
  "interview",
  "homeCheck",
  "approved",
  "rejected",
  "cancelled",
  "completed",
];

// ==================================================
// Handle Validation Errors
// ==================================================
// • Reads validation errors generated by express-validator.
// • Stops the request when one or more fields are invalid.
// • Returns validation errors in a consistent response format.
// ==================================================

const handleValidationErrors = (req, res, next) => {
  const errors = validationResult(req);

  if (!errors.isEmpty()) {
    return res.status(400).json({
      success: false,
      message: "Validation failed",
      errors: errors.array().map((error) => ({
        field: error.path,
        message: error.msg,
        value: error.value,
      })),
    });
  }

  next();
};

// ==================================================
// Create Adoption Request Validation
// ==================================================
// • Requires a valid animal ID.
// • Allows an optional message.
// • Trims the message and limits its length.
// ==================================================

const createRequestValidation = [
  body("animalId")
    .notEmpty()
    .withMessage("Animal ID is required")
    .bail()
    .isMongoId()
    .withMessage("Invalid animal ID"),

  body("message")
    .optional({
      nullable: true,
      checkFalsy: true,
    })
    .isString()
    .withMessage("Message must be a string")
    .bail()
    .trim()
    .isLength({
      max: 1000,
    })
    .withMessage(
      "Message cannot exceed 1000 characters",
    ),

  handleValidationErrors,
];

// ==================================================
// Get Current Adopter Requests Validation
// ==================================================
// • Allows filtering the current adopter requests by status.
// • Accepts only supported adoption request statuses.
// ==================================================

const getMyRequestsValidation = [
  query("status")
    .optional({
      checkFalsy: true,
    })
    .isString()
    .withMessage("Status must be a string")
    .bail()
    .isIn(requestStatuses)
    .withMessage(
      "Invalid adoption request status",
    ),

  handleValidationErrors,
];

// ==================================================
// Get Shelter Adoption Requests Validation
// ==================================================
// • Allows filtering shelter requests by status.
// • Allows the Super Admin to provide a shelter ID.
// • Allows filtering by animal ID or adopter ID.
// • Validates all provided MongoDB IDs.
// ==================================================

const getShelterRequestsValidation = [
  query("status")
    .optional({
      checkFalsy: true,
    })
    .isString()
    .withMessage("Status must be a string")
    .bail()
    .isIn(requestStatuses)
    .withMessage(
      "Invalid adoption request status",
    ),

  query("shelterId")
    .optional({
      checkFalsy: true,
    })
    .isMongoId()
    .withMessage("Invalid shelter ID"),

  query("animalId")
    .optional({
      checkFalsy: true,
    })
    .isMongoId()
    .withMessage("Invalid animal ID"),

  query("adopterId")
    .optional({
      checkFalsy: true,
    })
    .isMongoId()
    .withMessage("Invalid adopter ID"),

  handleValidationErrors,
];

